#!/usr/bin/env python3
"""Bake the 32 NFL team logos into the app as small data URIs (src/js/02b-team-logos.js).

Why: NFL_LOGO() used to fetch desktop-sized transforms from NFL's CDN — 32 network
images every time the team dropdown opened, slow and flaky on mobile. Baked at 48px
they total well under 150KB, render instantly, and work offline. Rerun whenever a
team rebrands; the CDN stays as the runtime fallback for any code not baked."""
import base64, io, os, sys, urllib.request
try:
    from PIL import Image
except ImportError:
    sys.exit("needs PIL (run with the pyenv nfl interpreter)")

TEAMS = ["ARI","ATL","BAL","BUF","CAR","CHI","CIN","CLE","DAL","DEN","DET","GB","HOU","IND",
         "JAX","KC","LA","LAC","LV","MIA","MIN","NE","NO","NYG","NYJ","PHI","PIT","SEA","SF","TB","TEN","WAS"]
URL = "https://static.www.nfl.com/t_headshot_desktop/f_auto/league/api/clubs/logos/{c}"
# Two tiers: 48px for the icons everywhere (the dropdown, the rails, the feed), and 192px
# for the few places a logo is drawn big — the game hero's watermark, the player card's —
# where the 48px tier scaled four times over went visibly soft. NFL_LOGO_HI() serves the
# second tier; it costs about 200KB more in the built page, once.
SIZE = 48
SIZE_HI = 192

out = {}
out_hi = {}
total = 0
total_hi = 0
for c in TEAMS:
    cdn = URL.format(c="JAC" if c == "JAX" else c)
    req = urllib.request.Request(cdn, headers={"User-Agent": "triplecrown-build"})
    with urllib.request.urlopen(req, timeout=30) as r:
        raw = r.read()
    src = Image.open(io.BytesIO(raw)).convert("RGBA")
    for size, store, cap in ((SIZE, out, 8000), (SIZE_HI, out_hi, 24000)):
        im = src.copy()
        im.thumbnail((size, size), Image.LANCZOS)
        buf = io.BytesIO()
        im.save(buf, "WEBP", quality=82, method=6)
        b = buf.getvalue()
        if len(b) > cap:  # webp should never be this big; keep the file honest
            sys.exit(f"{c}@{size}: {len(b)}B — too big, inspect")
        store[c] = "data:image/webp;base64," + base64.b64encode(b).decode()
        if size == SIZE: total += len(b)
        else: total_hi += len(b)
    print(f"  {c}: {len(base64.b64decode(out[c].split(',',1)[1]))}B / {len(base64.b64decode(out_hi[c].split(',',1)[1]))}B")

js = ("// GENERATED by tools/bake_team_logos.py — 32 team logos as webp data URIs: 48px for\n"
      "// the icons (NFL_LOGO), 192px for the few big renders (NFL_LOGO_HI, 01-constants.js).\n"
      "// The CDN remains the fallback for any code not baked.\n"
      "const TEAM_LOGO_DATA = {\n"
      + "".join(f'  {c}: "{u}",\n' for c, u in out.items())
      + "};\n"
      "const TEAM_LOGO_DATA_HI = {\n"
      + "".join(f'  {c}: "{u}",\n' for c, u in out_hi.items())
      + "};\n")
open(os.path.join(os.path.dirname(__file__), "..", "src", "js", "02b-team-logos.js"), "w").write(js)
print(f"baked {len(out)} logos, {total/1024:.0f}KB at 48px + {total_hi/1024:.0f}KB at 192px → src/js/02b-team-logos.js")
